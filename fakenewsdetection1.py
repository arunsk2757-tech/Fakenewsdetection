def predict_news(text):
    inputs = tokenizer(
        text,
        return_tensors="pt",
        truncation=True,
        padding=True,
        max_length=128
    )

    inputs = {key: val.to(device) for key, val in inputs.items()}

    model.eval()
    with torch.no_grad():
        outputs = model(**inputs)

    # 🔥 ADD THIS LINE (DEBUG)
    print("LOGITS:", outputs.logits)

    probs = F.softmax(outputs.logits, dim=1)

    fake_prob = probs[0][0].item()
